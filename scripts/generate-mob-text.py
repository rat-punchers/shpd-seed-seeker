#!/usr/bin/env python3
"""Generate map inspection mob text from the pinned Java game's English messages.

Run with --source-dir containing actors.properties and levels.properties for
an offline regeneration. Otherwise fetch the pinned files. Covers every mob kind the level
map draws (`visuals/actors.rs`). Only static description text is included, as
in generate-item-text.py.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re
from urllib.request import urlopen

REVISION = "57a4e06a4caf162446d1c28caa7983f0493fecf0"
ROOT = Path(__file__).resolve().parents[1]
BASE = f"https://raw.githubusercontent.com/00-Evan/shattered-pixel-dungeon/{REVISION}/core/src/main/assets/messages/"
FILES = {
    "actors.properties": "actors/actors.properties",
    "levels.properties": "levels/levels.properties",
}
ACTORS = ROOT / "crates/seedfinder-core/src/level_map/visuals/actors.rs"
OUTPUT = ROOT / "crates/seedfinder-core/src/level_map/mob_text.rs"
# Map kinds named differently from their Java message keys.
ALIASES = {
    "ArmoredStatue": "Statue",
    "VaultDm100": "DM100",
    "VaultDm200": "DM200",
    "VaultGhoul": "Ghoul",
    "VaultGolem": "Golem",
}
# Colour variants share their base mob's text.
VARIANT = re.compile(r"^(?:Red|Blue|Green|Purple)(?=[A-Z])")


def normalize(value):
    return re.sub(r"[^a-z0-9]", "", value.lower())


def static_text(desc):
    paragraphs = []
    for paragraph in desc.split("\n\n"):
        sentences = re.split(r"(?<=[.!?])\s+", paragraph)
        static = [s for s in sentences if not re.search(r"%(?:\d+\$)?[\d.]*[a-zA-Z]", s)]
        if static:
            paragraphs.append(" ".join(static))
    return "\n\n".join(paragraphs).replace("_", "").replace("%%", "%")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source-dir", type=Path)
    args = parser.parse_args()
    sources = {
        name: (args.source_dir / name).read_bytes() if args.source_dir else urlopen(BASE + path).read()
        for name, path in FILES.items()
    }
    messages = {}
    lines = [line for data in sources.values() for line in data.decode().splitlines()]
    for line in lines:
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, value = line.split("=", 1)
        messages[key] = value.replace(r"\n", "\n").replace(r"\'", "'").replace(r'\"', '"')
    by_id = {}
    for key, name in messages.items():
        match = re.fullmatch(r"(?:actors\.mobs|levels\.rooms\.special)\.(?:\w+\.)*([\w$]+)\.name", key)
        if not match or "%" in name:
            continue
        prefix = key[:-5]
        desc = next((messages[prefix + s] for s in (".desc", ".desc_1", ".desc_inactive") if prefix + s in messages), "")
        desc = static_text(desc)
        if desc:
            identifier = normalize(match.group(1).rsplit("$", 1)[-1])
            by_id.setdefault(identifier, (name[0].upper() + name[1:], desc))
    arms = re.findall(r'^\s*((?:"\w+"\s*\|\s*)*"\w+")\s*=>', ACTORS.read_text(), re.M)
    kinds = sorted({kind for arm in arms for kind in re.findall(r'"(\w+)"', arm)})
    records = {}
    for kind in kinds:
        text = by_id.get(normalize(ALIASES.get(kind, VARIANT.sub("", kind))))
        if text:
            records[kind] = text
        else:
            print(f"No Java description: {kind}")
    output = [
        "// Generated by scripts/generate-mob-text.py; do not edit.",
        "// Shattered Pixel Dungeon v4.0.2, GPL-3.0-or-later.",
        f"// Source revision: {REVISION}",
        *(f"// {name}: sha256 {hashlib.sha256(data).hexdigest()}" for name, data in sources.items()),
        "#[rustfmt::skip]",
        "pub(super) const MOB_TEXT: &[(&str, &str, &str)] = &[",
    ]
    for kind, (name, desc) in sorted(records.items()):
        output.append("    (" + ", ".join(json.dumps(s, ensure_ascii=False) for s in (kind, name, desc)) + "),")
    output += ["];", ""]
    OUTPUT.write_text("\n".join(output))
    print(f"Generated {len(records)} of {len(kinds)} mob descriptions")


if __name__ == "__main__":
    main()
